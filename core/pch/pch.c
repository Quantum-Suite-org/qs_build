    char *pch_path=tc->is_msvc
        ? qs_arena_sprintf(a,"%s/pch.pch",dir)
        : qs_arena_sprintf(a,"%s/pch.hpp.gch",dir);
    qs_result_t r=qs_pch_generate_header(a,m,hdr_path,diag);
    if (r!=QS_OK) return r;

    const char *argv[ARGV_MAX]; int ac=0;
    argv_push(argv,&ac,tc->executable);
