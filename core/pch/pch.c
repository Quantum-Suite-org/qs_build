/* ── PCH validity check ──────────────────────────────────────────────────── */
qs_bool_t qs_pch_is_valid(qs_arena_t *a, const qs_pch_info_t *pch,
                             const qs_manifest_t *m) {
    if (!pch->valid) return QS_FALSE;
    qs_stat_t st; qs_fs_stat(pch->pch_path,&st);
    if (!st.exists) return QS_FALSE;
    /* Check if any header is newer than the PCH */
    for (qs_size_t i=0;i<m->headers.len;i++) {
        char *hp=qs_arena_str_to_cstr(a,m->headers.data[i]);
        qs_stat_t hs; qs_fs_stat(hp,&hs);
        if (hs.mtime_us > pch->mtime_us) return QS_FALSE;
    }
    return QS_TRUE;
}

/* ── Flags to USE an existing PCH ────────────────────────────────────────── */
qs_result_t qs_pch_use_flags_c(qs_arena_t *a, const qs_pch_info_t *pch,
                                  const qs_toolchain_t *tc, qs_str_vec_t *flags) {
    if (tc->is_msvc) {
        qs_str_vec_push(flags,qs_str_from_cstr(qs_arena_sprintf(a,"/Yu%s",pch->header_path)));
        qs_str_vec_push(flags,qs_str_from_cstr(qs_arena_sprintf(a,"/Fp%s",pch->pch_path)));
    } else {
        qs_str_vec_push(flags,qs_str_from_cstr("-include-pch"));
        qs_str_vec_push(flags,qs_str_from_cstr(pch->pch_path));
    }
    return QS_OK;
}
qs_result_t qs_pch_use_flags_cpp(qs_arena_t *a, const qs_pch_info_t *pch,
                                    const qs_toolchain_t *tc, qs_str_vec_t *flags) {
    return qs_pch_use_flags_c(a,pch,tc,flags);
}
