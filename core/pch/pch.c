/*
 * pch.c — Precompiled header management for all supported languages.
 *
 * PCH AUTO-RULE: enabled automatically when a folder has >= QS_PCH_THRESHOLD (30)
 * source files. The amalgam header is generated from all public headers in the
 * manifest, then compiled once. Every subsequent TU includes it via -include-pch
 * (clang/gcc) or /Yu (MSVC).
 *
 * Per-language PCH strategies:
 *   C/C++   → clang -x c-header / g++ -x c++-header / cl /Yc
 *   C#      → dotnet build with a shared AssemblyInfo reference cache
 *   Java    → javac -h (header generation) + shared classpath precompile
 *   Python  → python -m compileall → .pyc byte-code seed cache
 *   Go      → go build -pkgdir (precompile stdlib into a custom pkg dir)
 *   Ruby    → ruby --disable=gems preload + Marshal dump of require cache
 *   Rust    → cargo build --target-dir with sysroot precompile
 *   Zig     → zig build-lib for a precompiled module cache
 */
#include "qs_pch.h"
#include "qs_fs.h"
#include "qs_process.h"
#include "qs_path.h"
#include "qs_str.h"
#include "qs_hash.h"
#include <stdio.h>
#include <string.h>
#include <stdlib.h>

/* ── Threshold check ─────────────────────────────────────────────────────── */
qs_bool_t qs_pch_should_enable(const qs_manifest_t *m) {
    if (m->enable_pch) return QS_TRUE;
    return m->sources.len >= QS_PCH_THRESHOLD ? QS_TRUE : QS_FALSE;
}

/* ── PCH output directory ────────────────────────────────────────────────── */
static char *pch_dir(qs_arena_t *a, const qs_manifest_t *m, const char *lang) {
    return qs_arena_sprintf(a,"%s/.qs_pch/%s",
        QS_STR_IS_EMPTY(m->out_dir)?"./out":(const char*)m->out_dir.ptr,
        lang);
}

/* ══════════════════════════════════════════════════════════════════════════
 * Amalgam header generation
 * Scans all .h/.hpp in the manifest's include dirs and generates a single
 * header that #includes them all, suitable for PCH compilation.
 * ══════════════════════════════════════════════════════════════════════════ */
qs_result_t qs_pch_generate_header(qs_arena_t *a, const qs_manifest_t *m,
                                     const char *out_path, qs_diag_engine_t *diag) {
    FILE *f=fopen(out_path,"w");
    if (!f) {
        qs_diag_emit_simple(diag,QS_SEV_ERROR,"pch","QSB-PCH001",QS_LOC_UNKNOWN,
            qs_arena_sprintf(a,"cannot create pch header: %s",out_path));
        return QS_ERROR_IO;
    }
    fprintf(f,"/* Auto-generated PCH amalgam — do not edit */\n");
    fprintf(f,"/* Generated by qs_build for module: %.*s */\n\n",
        (int)m->name.len,(const char*)m->name.ptr);

    /* Standard preamble for C/C++ */
    if (m->language==QS_LANG_C||m->language==QS_LANG_CPP) {
        fprintf(f,"#include <stdint.h>\n#include <stddef.h>\n");
        fprintf(f,"#include <string.h>\n#include <stdio.h>\n");
        fprintf(f,"#include <stdlib.h>\n#include <assert.h>\n");
        if (m->language==QS_LANG_CPP) {
            fprintf(f,"#include <string>\n#include <vector>\n");
            fprintf(f,"#include <unordered_map>\n#include <memory>\n");
            fprintf(f,"#include <functional>\n#include <algorithm>\n");
            fprintf(f,"#include <optional>\n#include <variant>\n");
            fprintf(f,"#include <span>\n#include <ranges>\n");
        }
        fprintf(f,"\n/* Module headers */\n");
    }

    /* Include all headers listed in manifest */
    for (qs_size_t i=0;i<m->headers.len;i++) {
        qs_str_t h=m->headers.data[i];
        fprintf(f,"#include \"%.*s\"\n",(int)h.len,(const char*)h.ptr);
    }

    /* Scan include_dirs for header files if no explicit list */
    if (!m->headers.len) {
        for (qs_size_t i=0;i<m->include_dirs.len;i++) {
            qs_str_t idir=m->include_dirs.data[i];
            char *idir_c=qs_arena_str_to_cstr(a,idir);
            qs_str_vec_t found; qs_str_vec_init(&found,a);
            const char *hexts[]={".h",".hpp",".hxx",".hh",NULL};
            qs_fs_scan_sources(a,idir_c,hexts,&found);
            for (qs_size_t j=0;j<found.len;j++)
                fprintf(f,"#include \"%.*s\"\n",(int)found.data[j].len,(const char*)found.data[j].ptr);
        }
    }

    fprintf(f,"\n/* end of qs_build pch amalgam */\n");
    fclose(f);
    return QS_OK;
}

/* ── Shared: build argv helper ───────────────────────────────────────────── */
#define ARGV_MAX 256
static void argv_push(const char **av, int *ac, const char *s) {
    if (*ac<ARGV_MAX-1) { av[(*ac)++]=s; av[*ac]=NULL; }
}

/* ══════════════════════════════════════════════════════════════════════════
 * C PCH: clang -x c-header / gcc -x c-header / cl.exe /Yc
 * ══════════════════════════════════════════════════════════════════════════ */
qs_result_t qs_pch_build_c(qs_arena_t *a, const qs_manifest_t *m,
                              const qs_toolchain_t *tc, qs_pch_info_t *out,
                              qs_diag_engine_t *diag) {
    char *dir=pch_dir(a,m,"c");
    qs_fs_mkdir_p(dir);
    char *hdr_path=qs_arena_sprintf(a,"%s/pch.h",dir);
    char *pch_path=qs_arena_sprintf(a,"%s/pch.h.gch",dir);
    qs_result_t r=qs_pch_generate_header(a,m,hdr_path,diag);
    if (r!=QS_OK) return r;

    const char *argv[ARGV_MAX]; int ac=0;
    argv_push(argv,&ac,tc->executable);
    if (tc->is_msvc) {
        argv_push(argv,&ac,qs_arena_sprintf(a,"/Yc%s",hdr_path));
        argv_push(argv,&ac,qs_arena_sprintf(a,"/Fp%s",pch_path));
    } else {
        argv_push(argv,&ac,"-x"); argv_push(argv,&ac,"c-header");
        argv_push(argv,&ac,qs_arena_sprintf(a,"-std=%s",
            QS_STR_IS_EMPTY(m->standard)?"c17":(const char*)m->standard.ptr));
        for (qs_size_t i=0;i<m->include_dirs.len;i++)
            argv_push(argv,&ac,qs_arena_sprintf(a,"-I%.*s",
                (int)m->include_dirs.data[i].len,(const char*)m->include_dirs.data[i].ptr));
        for (qs_size_t i=0;i<m->defines.len;i++)
            argv_push(argv,&ac,qs_arena_sprintf(a,"-D%.*s",
                (int)m->defines.data[i].len,(const char*)m->defines.data[i].ptr));
        argv_push(argv,&ac,"-o"); argv_push(argv,&ac,pch_path);
        argv_push(argv,&ac,hdr_path);
    }

    qs_proc_result_t pr;
    r=qs_proc_run(a,argv,NULL,120000000ULL,&pr);
    if (r!=QS_OK) return r;
    if (pr.exit_code!=0) {
        qs_diag_ingest_tool_output(diag,a,QS_STR("clang"),pr.stderr_text,pr.exit_code);
        return QS_ERROR_PCH;
    }
    out->lang=QS_LANG_C;
    out->pch_path=pch_path;
    out->header_path=hdr_path;
    out->valid=QS_TRUE;
    qs_stat_t st; qs_fs_stat(pch_path,&st);
    out->mtime_us=st.mtime_us;
    return QS_OK;
}

/* ══════════════════════════════════════════════════════════════════════════
 * C++ PCH
 * ══════════════════════════════════════════════════════════════════════════ */
