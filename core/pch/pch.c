    argv_push(argv,&ac,tc->executable);
    argv_push(argv,&ac,"-m"); argv_push(argv,&ac,"compileall");
    argv_push(argv,&ac,"-b"); /* write .pyc beside .py */
    argv_push(argv,&ac,"-j"); argv_push(argv,&ac,"0"); /* parallel */
    argv_push(argv,&ac,"-q");
    argv_push(argv,&ac,src_root);
    qs_proc_result_t pr; qs_result_t r=qs_proc_run(a,argv,NULL,120000000ULL,&pr);
    if (r!=QS_OK) return r;
