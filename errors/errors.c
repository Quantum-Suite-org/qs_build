/*
 * errors/errors.c — Complete error catalogue for qs_build.
 *
 * One qs_error_entry_t row per QSB-XXXnnn code.  The table is terminated
 * by a sentinel entry (code == NULL).  qs_error_lookup() does a linear
 * scan — the catalogue is only ~200 entries so a hash table is unnecessary.
 *
 * Public API:
 *   qs_error_lookup()       find entry by code string
 *   qs_error_emit()         look up + emit via diag engine (convenience)
 *   qs_error_count()        total number of registered codes
 *   qs_error_catalog_ptr()  raw array pointer for iteration
 */
