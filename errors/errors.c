/* ── Public API implementation ───────────────────────────────────────────── */

const qs_error_entry_t *qs_error_catalog_ptr(void) {
    return CATALOG;
}

qs_size_t qs_error_count(void) {
    qs_size_t n = 0;
    while (CATALOG[n].code) n++;
    return n;
}

const qs_error_entry_t *qs_error_lookup(const char *code) {
    if (!code) return NULL;
    for (const qs_error_entry_t *e = CATALOG; e->code; e++) {
        if (strcmp(e->code, code) == 0) return e;
    }
    return NULL;
}

void qs_error_emit(qs_diag_engine_t *engine,
                   qs_arena_t       *arena,
                   const char       *code,
                   qs_severity_t     sev,
                   const char       *tool,
                   qs_loc_t          loc,
                   const char       *message) {
    const qs_error_entry_t *entry = qs_error_lookup(code);

    qs_diag_t d;
    memset(&d, 0, sizeof(d));

    d.code    = qs_str_from_cstr(code ? code : "");
    d.tool    = qs_str_from_cstr(tool ? tool : "qs_build");
    d.loc     = loc;

    /* Severity: caller may pass (qs_severity_t)-1 to use catalogue default */
    d.sev = ((int)sev == -1)
            ? (entry ? entry->default_sev : QS_SEV_ERROR)
            : sev;

    /* Message: caller may pass NULL to use the catalogue name */
    if (message) {
        d.message = qs_str_from_cstr(message);
    } else if (entry && entry->name) {
        d.message = qs_str_from_cstr(entry->name);
    } else {
        d.message = qs_str_from_cstr("(no message)");
    }

    /* Populate hint and URL from the catalogue */
    if (entry) {
        if (entry->hint) d.hint = qs_str_from_cstr(entry->hint);
        if (entry->url)  d.url  = qs_str_from_cstr(entry->url);
    }

    qs_diag_emit(engine, d);

    QS_UNUSED(arena); /* reserved for future arena-duped strings */
}
